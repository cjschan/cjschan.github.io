def sec(key, hw_due=None, quiz_n=None, test_n=None, hw_items=None):
    """A section row with its homework (due Sunday), quiz and test appended to the assessments."""
    r = ROWS[key]
    name = key.rstrip("ab")
    homework = hw_items if hw_items is not None else ([hw(name, hw_due)] if hw_due else [])
    extra = homework + ([quiz(quiz_n)] if quiz_n else []) + (test(test_n) if test_n else [])
    return dict(r, key=key, assessments=r["assessments"] + extra)

